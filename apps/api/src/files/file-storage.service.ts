import { Injectable, type OnModuleInit } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { randomUUID } from 'node:crypto';
import { createWriteStream } from 'node:fs';
import { mkdir, rename, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { pipeline } from 'node:stream/promises';
import type { Readable } from 'node:stream';

const DEFAULT_FILES_DIR = '.files';
const TMP_DIR = '.tmp';

export interface TempFile {
  /** Absolute path of the temporary file. */
  path: string;
  /** Bytes actually written, not what the client claimed. */
  size: number;
}

/**
 * Stores file bytes on the local disk under FILES_DIR:
 *
 *   .tmp/<uuid>                    uploads in progress
 *   meetings/<meetingId>/<fileId>  committed files (`storageKey` is this relative path)
 *
 * Names sent by clients never reach a path: every name here is generated by the server.
 */
@Injectable()
export class FileStorageService implements OnModuleInit {
  private readonly root: string;

  constructor(config: ConfigService) {
    // Resolved once: a relative path would otherwise depend on where the process started.
    this.root = resolve(config.get<string>('FILES_DIR') ?? DEFAULT_FILES_DIR);
  }

  /** A crash in the middle of an upload leaves a temp file behind; nothing else owns them. */
  async onModuleInit(): Promise<void> {
    const tmp = join(this.root, TMP_DIR);
    await rm(tmp, { recursive: true, force: true });
    await mkdir(tmp, { recursive: true });
  }

  /** Streams the data to a new temp file; removes the partial file if the stream fails. */
  async writeTemp(source: Readable): Promise<TempFile> {
    const path = join(this.root, TMP_DIR, randomUUID());
    const target = createWriteStream(path, { flags: 'wx' });

    try {
      await pipeline(source, target);
    } catch (error) {
      await this.removeTemp(path);
      throw error;
    }

    return { path, size: target.bytesWritten };
  }

  async removeTemp(path: string): Promise<void> {
    await rm(path, { force: true });
  }

  keyFor(meetingId: string, fileId: string): string {
    return `meetings/${meetingId}/${fileId}`;
  }

  /** Moves a finished temp file to its permanent place; same volume, so the move is atomic. */
  async commit(tempPath: string, storageKey: string): Promise<void> {
    const target = this.resolveKey(storageKey);
    await mkdir(dirname(target), { recursive: true });
    await rename(tempPath, target);
  }

  async remove(storageKey: string): Promise<void> {
    await rm(this.resolveKey(storageKey), { force: true });
  }

  private resolveKey(storageKey: string): string {
    return join(this.root, ...storageKey.split('/'));
  }
}
